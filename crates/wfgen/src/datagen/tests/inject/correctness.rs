#[test]
fn test_inject_use_predicates_are_step_scoped_and_typed() {
    let input = r#"
#[duration=5s]
scenario inject_step_scope<seed=42> {
    background {
        stream LoginWindow gen 40/s
    }
    injection {
        // 40 个实体 × (1 + 1) = 80 条注入（配额 200）
        hit<src_ip: 40> for bool_chain LoginWindow {
            use(success=false) x 1
            then use(success=true) x 1
        }
    }
}
"#;
    let wfg = parse_wfg(input).unwrap();
    let schemas = vec![make_login_schema()];
    let plans = vec![make_bool_chain_plan()];

    let result = generate(&wfg, &schemas, &plans).unwrap();
    assert_eq!(result.events.len(), 200);

    let mut by_entity: std::collections::HashMap<
        String,
        Vec<(chrono::DateTime<chrono::Utc>, bool)>,
    > = std::collections::HashMap::new();
    for event in &result.events {
        let Some(entity) = event.fields.get("username").and_then(|v| v.as_str()) else {
            continue;
        };
        if !entity.starts_with("hit_username_") {
            continue;
        }
        let Some(success) = event.fields.get("success").and_then(|v| v.as_bool()) else {
            panic!(
                "inject event should keep bool type for success, got {:?}",
                event.fields.get("success")
            );
        };
        by_entity
            .entry(entity.to_string())
            .or_default()
            .push((event.timestamp, success));
    }

    assert!(
        !by_entity.is_empty(),
        "expected inject entities with generated username prefix"
    );

    for (entity, seq) in &mut by_entity {
        seq.sort_by_key(|(ts, _)| *ts);
        assert!(
            seq.len() >= 2,
            "entity {} should have at least 2 injected events, got {}",
            entity,
            seq.len()
        );
        assert!(
            !seq[0].1,
            "entity {} first step should be success=false, got {:?}",
            entity, seq[0].1
        );
        assert!(
            seq[1].1,
            "entity {} second step should be success=true, got {:?}",
            entity, seq[1].1
        );
    }
}

#[test]
fn test_inject_near_miss_no_trigger() {
    // near_miss 的条数就是写的 `x N`：x 4 < 阈值 5，故不成簇、不触发
    let input = r#"
#[duration=10s]
scenario inject_nm<seed=42> {
    background {
        stream LoginWindow gen 100/s
    }
    injection {
        // 100 个实体 × 每个 4 条 = 400 条注入（配额 1000）
        near_miss<src_ip: 100> for brute_force LoginWindow {
            use(action="failed") x 4
        }
    }
}
"#;
    let wfg = parse_wfg(input).unwrap();
    let schemas = vec![make_login_schema()];
    let plans = vec![make_brute_force_plan()];

    let result = generate(&wfg, &schemas, &plans).unwrap();
    assert_eq!(result.events.len(), 1000);

    // Run oracle — near-miss clusters should NOT produce alerts
    let start = "2024-01-01T00:00:00Z".parse().unwrap();
    let duration = Duration::from_secs(3600);
    let oracle = run_oracle(&result.events, &plans, &start, &duration, None).unwrap();
    assert_eq!(
        oracle.alerts.len(),
        0,
        "near-miss clusters should not trigger any alerts"
    );
}

#[test]
fn test_inject_hit_triggers_oracle() {
    let input = r#"
#[duration=10s]
scenario inject_oracle<seed=42> {
    background {
        stream LoginWindow gen 100/s
    }
    injection {
        // 100 个实体 × 每个 5 条 = 500 条注入 → 100 个簇
        hit<src_ip: 100> for brute_force LoginWindow {
            use(action="failed") x 5
        }
    }
}
"#;
    let wfg = parse_wfg(input).unwrap();
    let schemas = vec![make_login_schema()];
    let plans = vec![make_brute_force_plan()];

    let result = generate(&wfg, &schemas, &plans).unwrap();

    // Run oracle — hit clusters should produce alerts
    let start = "2024-01-01T00:00:00Z".parse().unwrap();
    let duration = Duration::from_secs(3600);
    let oracle = run_oracle(&result.events, &plans, &start, &duration, None).unwrap();

    // 100 个实体 × 每个 5 条 = 500 条注入 / 每簇 5 条 = 100 个簇 → 100 条告警
    assert_eq!(
        oracle.alerts.len(),
        100,
        "expected 100 alerts from 100 hit clusters, got {}",
        oracle.alerts.len()
    );

    // All alerts should have correct rule name and score
    for alert in &oracle.alerts {
        assert_eq!(alert.rule_name, "brute_force");
        assert!((alert.score - 85.0).abs() < f64::EPSILON);
        assert_eq!(alert.entity_type, "ip");
    }
}

#[test]
fn test_inject_mode_counts_are_independent_and_additive() {
    // 三种模式的数量各自写死、互不共享预算：
    //   60×5 + 25×4 + 200×1 = 600 条注入；配额 1000，其余 400 条为背景
    let input = r#"
#[duration=10s]
scenario inject_budget<seed=42> {
    background {
        stream LoginWindow gen 100/s
    }
    injection {
        hit<src_ip: 60> for brute_force LoginWindow {
            use(action="failed") x 5
        }
        near_miss<src_ip: 25> for brute_force LoginWindow {
            use(action="failed") x 4
        }
        miss<src_ip: 200> for brute_force LoginWindow {
            use(action="success") x 1
        }
    }
}
"#;
    let wfg = parse_wfg(input).unwrap();
    let schemas = vec![make_login_schema()];
    let plans = vec![make_brute_force_plan()];

    let result = generate(&wfg, &schemas, &plans).unwrap();
    // 注入量不超出配额，因此总条数 = max(配额, 注入量) = 1000
    assert_eq!(result.events.len(), 1000);

    let injected = result
        .events
        .iter()
        .filter(|e| {
            e.fields
                .get("src_ip")
                .and_then(|v| v.as_str())
                .is_some_and(|s| s.starts_with("10.") && s.len() <= 15)
        })
        .count();
    assert!(
        injected >= 600,
        "三种模式的注入量必须各自写死并相加（60×5 + 25×4 + 200×1 = 600），实际 {injected}"
    );
}

#[test]
fn test_inject_deterministic() {
    let input = r#"
#[duration=5s]
scenario inject_det<seed=42> {
    background {
        stream LoginWindow gen 100/s
    }
    injection {
        hit<src_ip: 30> for brute_force LoginWindow {
            use(action="failed") x 5
        }
    }
}
"#;
    let wfg = parse_wfg(input).unwrap();
    let schemas = vec![make_login_schema()];
    let plans = vec![make_brute_force_plan()];

    let result1 = generate(&wfg, &schemas, &plans).unwrap();
    let result2 = generate(&wfg, &schemas, &plans).unwrap();

    assert_eq!(result1.events.len(), result2.events.len());
    for (e1, e2) in result1.events.iter().zip(result2.events.iter()) {
        assert_eq!(e1.timestamp, e2.timestamp);
        assert_eq!(e1.fields, e2.fields);
    }
}
